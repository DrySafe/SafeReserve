export const money = cents => new Intl.NumberFormat('pt-BR', { style: 'currency', currency: 'BRL', maximumFractionDigits: 0 }).format(cents / 100);
export function dateKey(date = new Date(), timezone = 'America/Sao_Paulo') {
  const parts = new Intl.DateTimeFormat('en-CA', { timeZone: timezone, year: 'numeric', month: '2-digit', day: '2-digit' }).formatToParts(date);
  const get = key => parts.find(p => p.type === key).value;
  return `${get('year')}-${get('month')}-${get('day')}`;
}
export function nextDays(count = 21, timezone) {
  const today = dateKey(new Date(), timezone);
  return Array.from({ length: count }, (_, i) => { const d = new Date(`${today}T12:00:00Z`); d.setUTCDate(d.getUTCDate() + i); return dateKey(d, 'UTC'); });
}
export const overlaps = (start, end, busyStart, busyEnd) => start < busyEnd && end > busyStart;
export function compatibleProfessionals(pros, ids) { return pros.filter(p => ids.every(id => p.service_ids.includes(id))); }
// Demo uses the studio's fixed São Paulo offset. Production times are generated by PostgreSQL with the tenant's IANA zone.
export function demoAvailability({ date, duration, professionals, bookings = [], now = new Date() }) {
  if (new Date(`${date}T12:00:00Z`).getUTCDay() === 0) return [];
  const result = [];
  for (const pro of professionals) {
    const startOfDay = new Date(`${date}T09:00:00-03:00`).getTime();
    const endOfDay = new Date(`${date}T18:00:00-03:00`).getTime();
    const busy = bookings.filter(b => b.professional_id === pro.id && b.status !== 'cancelled').map(b => [new Date(b.starts_at).getTime(), new Date(b.ends_at).getTime()]);
    for (let start = startOfDay; start + duration * 60000 <= endOfDay; start += 15 * 60000) {
      const end = start + duration * 60000;
      if (start <= now.getTime() || busy.some(([a,b]) => overlaps(start, end, a, b))) continue;
      const adjacent = start === startOfDay || end === endOfDay || busy.some(([a,b]) => a === end || b === start);
      result.push({ starts_at: new Date(start).toISOString(), professional_id: pro.id, recommended: adjacent });
    }
  }
  return result.sort((a,b) => a.starts_at.localeCompare(b.starts_at) || Number(b.recommended) - Number(a.recommended));
}
export function uniqueSlots(slots) {
  const map = new Map();
  for (const s of slots) if (!map.has(s.starts_at) || s.recommended) map.set(s.starts_at, s);
  return [...map.values()].sort((a,b) => a.starts_at.localeCompare(b.starts_at));
}
export const phoneDigits = value => value.replace(/\D/g, '');
export function normalizePhone(value) {
  const digits = phoneDigits(value);
  if (/^55\d{10,11}$/.test(digits)) return '+' + digits;
  if (/^\d{10,11}$/.test(digits)) return '+55' + digits;
  throw new Error('Informe um WhatsApp válido com DDD.');
}
